#!/usr/bin/env python3
"""Liga cartoes de moda da loja a pacotes do original e prepara o catalogo do editor para eles.

Le out/recon/pack_texture_coverage.json (tools/pack_texture_coverage.py), junta as pecas com textura e categoria do
editor dos pacotes escolhidos (PACKS) ao catalogo atual e grava:
  - out/recon/pack_selection.json  (entrada de avatar_catalog_build.py --selection)
  - client/.../Scripts/Core/Economy/StorePackContent.cs  (cartao da loja -> ids de pecas liberadas)
A associacao cartao -> pacote e INFERIDA pelo nome (o servidor do original nao esta no APK); ver docs/STORE_BUNDLE_CONTENTS.md.
uso: python3 tools/build_pack_content.py && tools/venv/bin/python tools/avatar_catalog_build.py --selection out/recon/pack_selection.json --per-category 100
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UNITY = ROOT / 'client/AvatarWorldClient/Assets'
DATA_CS = UNITY / 'Scripts/Core/Avatar/AvatarCatalogData.cs'
OUT_CS = UNITY / 'Scripts/Core/Economy/StorePackContent.cs'
# id do cartao da loja -> pacote do original (flag de InventorySkinsBuildData)
PACKS = {
    'bundle-PB23': 'GalxeLiveShowP173',        # Show ao vivo
    'bundle-PB27': 'GraduationPartyP214',      # Festa (formatura) - "Festa de formatura 600" nos prints
    'bundle-PB20': 'StarsFashionP228',         # Pop Star
    'bundle-PB21': 'DaizyMiniCollectionP216',  # Moda Daisy
    'bundle-PB13': 'LuggageLuxuryFamilyP225',  # Ricos e Famosos
    'bundle-PB16': 'ToddlersExpansionP220',    # Crescendo
    'bundle-PB18': 'DriftCrewP244',            # Moda Drip
    'bundle-PB24': 'DayInTheParkP222',         # Ferias de Primavera
    'bundle-PB17': 'PrepToGlamP199',           # Estilista de Celebridades
}
CATEGORY_ORDER = ['Shirt', 'Bottom', 'Shoes', 'Accessory', 'Mouth', 'Eyebrows', 'HairBack']


def main():
    cov = json.loads((ROOT / 'out/recon/pack_texture_coverage.json').read_text(encoding='utf-8'))
    src = DATA_CS.read_text(encoding='utf-8')
    current = {m.group(1): re.findall(r'"([^"]+)"', m.group(2)) for m in re.finditer(r'string\[\] (\w+) =\s*\{(.*?)\};', src, re.S)}
    selection = {c: list(current[c]) for c in CATEGORY_ORDER}
    content = {}
    for offer, flag in PACKS.items():
        ids = []
        for piece in cov[flag]['pieces']:
            cat = piece['editor_category']
            if piece['texture'] != 'ok' or not cat: continue
            item = piece['skin'].lower()
            if item not in selection[cat]: selection[cat].append(item)
            ids.append(item)
        content[offer] = (flag, sorted(set(ids)))
    total = sum(len(v) for v in selection.values())
    (ROOT / 'out/recon/pack_selection.json').write_text(json.dumps({
        'status': 'provisional_review_only', 'total': total, 'items_by_category': selection}, indent=1), encoding='utf-8')
    lines = ['// <auto-generated> por tools/build_pack_content.py - nao editar a mao. </auto-generated>',
             'using System.Collections.Generic;', '', 'namespace AvatarWorld.Core.Economy', '{',
             '    /// <summary>',
             '    /// Pecas do editor de avatar liberadas por cada combo de moda da loja. Os pacotes vem de InventorySkinsBuildData do',
             '    /// original; a ligacao cartao -> pacote e inferida pelo nome (o servidor da loja nao esta no APK).',
             '    /// </summary>', '    public static class StorePackContent', '    {',
             '        public static readonly IReadOnlyDictionary<string, string[]> ItemsByOffer = new Dictionary<string, string[]>', '        {']
    for offer, (flag, ids) in content.items():
        lines.append(f'            // {flag}: {len(ids)} pecas')
        lines.append(f'            {{ "{offer}", new[]')
        lines.append('                {')
        lines += [f'                    "{i}",' for i in ids]
        lines += ['                } },']
    lines += ['        };', '    }', '}', '']
    OUT_CS.write_text('\n'.join(lines), encoding='utf-8')
    for o, (f, ids) in content.items(): print(o, f, len(ids))
    print('catalogo alvo:', total)


if __name__ == '__main__':
    main()
