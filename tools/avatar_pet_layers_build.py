#!/usr/bin/env python3
"""Gera os dados dos pets em camadas (cao e gato): raca, padrao, olhos, boca, sobrancelha, com paletas proprias.

O esqueleto Pet_<Especie>_Spine compoe o animal por skins independentes:
  Breed_X/Body/Body_Base_Color (tinta Body), Breed_X/Body/Body_Outline, Breed_X/Pattern/Pattern_N_Color (tinta Padrao),
  Breed_X/Eyebrows/Eyebrows_N_Color (so cao), Eyes_Outline_N + Eyes_Base_N_Color [+ Eyes_Gradient_N_Color] + Eyes_Pupils_N, Mouth/Mouth_N.
Cada skin passa por attachment -> regiao do atlas -> pagina -> textura unica por nome+dimensoes; so entra se tudo resolve.
Paletas (AWSpineColorsList Dog_/Cat_*) vao para Resources/AvatarSpine/pet-palettes.json.
Reaproveita os esqueletos/atlas copiados por avatar_pet_build.py (mesma pasta Pets/<Especie>), mas grava um pet.json em camadas.
uso: tools/venv/bin/python tools/avatar_pet_layers_build.py
"""
import collections
import gzip
import hashlib
import json
import re
import shutil
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UNITY = ROOT / 'client/AvatarWorldClient/Assets'
CLOTHING = UNITY / 'Resources/AvatarSpine/Clothing'
PETS_DIR = UNITY / 'Resources/AvatarSpine/Pets'
TEXTURES = ROOT / 'out/assets/Texture2D'
TEXT = ROOT / 'out/assets/TextAsset'
DUMPS = ROOT / 'out/recon/tasks/T034/pets'
LISTS = {'Dog': ['Dog_Body', 'Dog_Patterns', 'Dog_Eyes', 'Dog_Eyebrows'], 'Cat': ['Cat_Body', 'Cat_Patterns', 'Cat_Eyes'],
         'Horse': ['Horse_Body', 'Horse_Patterns', 'Horse_Eyes', 'Horse_Eyebrows', 'Horse_Hair', 'Horse_Tail']}
FILE_PREFIX = {'Horse': 'Pet_Horse'}  # os demais seguem Pet_<Especie>_Spine
IDLES = ['General/Chilling', 'General/Blinking']


def png_size(path):
    with open(path, 'rb') as fh:
        header = fh.read(24)
    return struct.unpack('>II', header[16:24])


def natural(value):
    return [int(p) if p.isdigit() else p for p in re.split(r'(\d+)', value)]


def parse_atlas(path):
    lines = path.read_text(encoding='utf-8-sig').splitlines()
    pages, regions, current = {}, {}, None
    for i in range(len(lines) - 1):
        line = lines[i].strip()
        if line.lower().endswith('.png') and lines[i + 1].strip().startswith('size:'):
            m = re.fullmatch(r'size:\s*(\d+)\s*,\s*(\d+)\s*', lines[i + 1].strip())
            current = line[:-4]
            pages[current.casefold()] = (current, (int(m.group(1)), int(m.group(2))))
        elif current and line and ':' not in line and not line.lower().endswith('.png'):
            regions[line] = current
    return pages, regions


def rgb(c):
    return [round(c['r'], 4), round(c['g'], 4), round(c['b'], 4)]


def export_palettes():
    wanted = {n for names in LISTS.values() for n in names}
    out = {}
    for line in gzip.open(ROOT / 'out/mb/PWC.AvatarMaker.AWSpineColorsList.jsonl.gz', 'rt'):
        r = json.loads(line)
        if r['m_Name'] in wanted:
            raw = r['AvatarMakerColors']
            raw = json.loads(raw) if isinstance(raw, str) else raw
            out[r['m_Name']] = [{'display': rgb(e['DisplayColor']), 'colors': [{'c': rgb(c)} for c in e['Colors']]} for e in raw]
    # JsonUtility nao le dicionarios: lista de {name, entries}
    data = {'lists': [{'name': n, 'entries': out[n]} for n in sorted(out)]}
    (UNITY / 'Resources/AvatarSpine/pet-palettes.json').write_text(json.dumps(data, separators=(',', ':')), encoding='utf-8')
    cs = UNITY / 'Scripts/Core/Avatar/PetPaletteData.cs'
    with open(cs, 'w', encoding='utf-8') as fh:
        fh.write('// <auto-generated> por tools/avatar_pet_layers_build.py - nao editar a mao. </auto-generated>\n')
        fh.write('using System.Collections.Generic;\n\nnamespace AvatarWorld.Core.Avatar\n{\n')
        fh.write('    /// <summary>Tamanho das paletas de pet (Resources/AvatarSpine/pet-palettes.json), para validar o save sem Resources.</summary>\n')
        fh.write('    public static class PetPaletteData\n    {\n        public static readonly Dictionary<string, int> Counts = new Dictionary<string, int>\n        {\n')
        for n in sorted(out):
            fh.write(f'            {{ "{n}", {len(out[n])} }},\n')
        fh.write('        };\n    }\n}\n')
    return {n: len(v) for n, v in out.items()}


def main():
    print('paletas', export_palettes())
    by_name = collections.defaultdict(list)
    for f in TEXTURES.iterdir():
        m = re.match(r'(.*)_(\d+)\.png$', f.name)
        if m:
            by_name[m.group(1).casefold()].append((f.name, int(m.group(2))))
    meta_template = next(iter(CLOTHING.glob('*.png.meta'))).read_text(encoding='utf-8')

    def ensure_meta(path):
        meta = Path(str(path) + '.meta')
        if meta.exists():
            return
        guid = hashlib.sha256(('avatarworld-re:' + path.relative_to(UNITY).as_posix()).encode()).hexdigest()[:32]
        text = re.sub(r'^guid:\s*[0-9a-fA-F]{32}\s*$', 'guid: ' + guid, meta_template, count=1, flags=re.M)
        meta.write_text('\n'.join(line.rstrip() for line in text.splitlines()) + '\n', encoding='utf-8')

    summary = {}
    for species in ('Dog', 'Cat', 'Horse'):
        prefix = FILE_PREFIX.get(species, f'Pet_{species}_Spine')
        atlas_file = next(TEXT.glob(f'{prefix}.atlas_*.txt'))
        skel_file = next(TEXT.glob(f'{prefix}.skel_*.txt'))
        pages, regions = parse_atlas(atlas_file)
        dump = json.loads((DUMPS / f'{species}.json').read_text(encoding='utf-8'))
        skins = {s['name']: s for s in dump['skins']}

        def unique_texture(page):
            name, size = pages[page.casefold()]
            cands = [x for x in by_name.get(name.casefold(), []) if png_size(TEXTURES / x[0]) == size]
            return cands[0] if len(cands) == 1 else None

        def pieces_of(skin_name, strict=True):
            if skin_name not in skins:
                return None
            pieces, seen = [], set()
            for att in skins[skin_name]['atts']:
                page = regions.get(att['path'] or '')
                if page is None or page in seen:
                    if page is None and strict:
                        return None
                    continue
                seen.add(page)
                found = unique_texture(page)
                if found is None:
                    if strict:
                        return None
                    continue
                filename, pid = found
                out_name = f'{page.casefold()}__{pid}.png'
                dest = CLOTHING / out_name
                if not dest.exists():
                    shutil.copyfile(TEXTURES / filename, dest)
                ensure_meta(dest)
                pieces.append({'template': 'Templates/' + page, 'file': out_name, 'skin': skin_name})
            return pieces or None

        breeds = []
        for letter in sorted({n.split('/')[0] for n in skins if n.startswith('Breed_')}):
            body = pieces_of(f'{letter}/Body/Body_Base_Color')
            outline = pieces_of(f'{letter}/Body/Body_Outline')
            if body is None or outline is None:
                print(species, letter, 'descartada (corpo nao resolve)')
                continue
            groups = {}
            for key, prefix in (('patterns', 'Pattern'), ('eyebrows', 'Eyebrows')):
                items = []
                for name in sorted((n for n in skins if n.startswith(f'{letter}/{prefix}/')), key=natural):
                    pieces = pieces_of(name)
                    if pieces:
                        items.append({'id': f'{prefix.lower()}_' + re.search(r'_(\d+)_Color$', name).group(1), 'pieces': pieces})
                groups[key] = items
            breeds.append({'id': letter.lower(), 'body': body, 'outline': outline, 'patterns': groups['patterns'], 'eyebrows': groups['eyebrows']})

        eyes = []
        for name in sorted((n for n in skins if n.startswith('Eyes_Base/')), key=natural):
            n = re.search(r'Eyes_Base_(\d+)_Color$', name).group(1)
            parts = {'base': pieces_of(name), 'outline': pieces_of(f'Eyes_Outline/Eyes_Outline_{n}'), 'pupils': pieces_of(f'Eyes_Pupils/Eyes_Pupils_{n}'),
                     'gradient': pieces_of(f'Eyes_Gradient/Eyes_Gradient_{n}_Color')}
            if parts['base'] and parts['outline'] and parts['pupils']:
                eyes.append({'id': f'eyes_{n}', 'base': parts['base'], 'outline': parts['outline'], 'pupils': parts['pupils'], 'gradient': parts['gradient'] or []})
        mouths = []
        for name in sorted((n for n in skins if n.startswith('Mouth/')), key=natural):
            pieces = pieces_of(name)
            if pieces:
                mouths.append({'id': 'mouth_' + name.rsplit('_', 1)[1], 'pieces': pieces})
        # crina (cabelo da frente + de tras, mesmo numero) e cauda: so o cavalo
        manes = []
        for name in sorted((n for n in skins if n.startswith('Hair/Hair_Front/')), key=natural):
            n = re.search(r'Hair_Front_(\d+)_Color$', name).group(1)
            front = pieces_of(name)
            back = pieces_of(f'Hair/Hair_Back/Hair_Back_{n}_Color')
            if front:
                manes.append({'id': f'mane_{n}', 'pieces': front + (back or [])})
        tails = []
        for name in sorted((n for n in skins if n.startswith('Tail/')), key=natural):
            pieces = pieces_of(name)
            if pieces:
                tails.append({'id': 'tail_' + re.search(r'Tail_(\d+)_Color$', name).group(1), 'pieces': pieces})
        base = pieces_of('default', False) or []
        idle = next((a for a in IDLES if a in dump['animations']), dump['animations'][0])

        out_dir = PETS_DIR / species
        out_dir.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(atlas_file, out_dir / 'Spine.atlas.txt')
        shutil.copyfile(skel_file, out_dir / 'Spine.skel.bytes')
        (out_dir / 'pet.json').write_text(json.dumps({'species': species, 'idle': idle, 'layered': True, 'basePieces': base, 'variants': [],
                                                       'breeds': breeds, 'eyes': eyes, 'mouths': mouths, 'manes': manes, 'tails': tails}, indent=1), encoding='utf-8')
        summary[species] = {
            'breeds': [b['id'] for b in breeds],
            'patterns': {b['id']: [p['id'] for p in b['patterns']] for b in breeds},
            'eyebrows': {b['id']: [p['id'] for p in b['eyebrows']] for b in breeds},
            'eyes': [e['id'] for e in eyes], 'mouths': [m['id'] for m in mouths],
            'manes': [m['id'] for m in manes], 'tails': [t['id'] for t in tails],
        }
        print(species, 'racas', len(breeds), 'padroes', sum(len(b['patterns']) for b in breeds), 'sobrancelhas', sum(len(b['eyebrows']) for b in breeds),
              'olhos', len(eyes), 'bocas', len(mouths), 'crinas', len(manes), 'caudas', len(tails), 'base', len(base))

    out = UNITY / 'Scripts/Core/Avatar/PetLayerCatalogData.cs'
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write('// <auto-generated> por tools/avatar_pet_layers_build.py - nao editar a mao. </auto-generated>\n')
        fh.write('using System.Collections.Generic;\n\nnamespace AvatarWorld.Core.Avatar\n{\n')
        fh.write('    /// <summary>Opcoes dos pets em camadas (cao e gato): racas, padroes por raca, sobrancelhas por raca, olhos e bocas.</summary>\n')
        fh.write('    public static class PetLayerCatalogData\n    {\n')
        fh.write('        public sealed class Layered\n        {\n            public string[] Breeds, Eyes, Mouths, Manes, Tails;\n'
                 '            public Dictionary<string, string[]> Patterns, Eyebrows;\n        }\n\n')
        fh.write('        public static readonly Dictionary<string, Layered> Species = new Dictionary<string, Layered>\n        {\n')

        def arr(ids):
            return 'new string[] { ' + ', '.join(f'"{i}"' for i in ids) + ' }'

        def dic(d):
            return 'new Dictionary<string, string[]> { ' + ', '.join(f'{{ "{k}", {arr(v)} }}' for k, v in d.items()) + ' }'
        for species, s in summary.items():
            fh.write(f'            {{ "{species}", new Layered\n            {{\n                Breeds = {arr(s["breeds"])},\n                Eyes = {arr(s["eyes"])},\n'
                     f'                Mouths = {arr(s["mouths"])},\n                Manes = {arr(s["manes"])},\n                Tails = {arr(s["tails"])},\n                Patterns = {dic(s["patterns"])},\n                Eyebrows = {dic(s["eyebrows"])},\n            }} }},\n')
        fh.write('        };\n    }\n}\n')


if __name__ == '__main__':
    main()
