#!/usr/bin/env python3
"""Exporta as paletas oficiais do editor de avatar (PWC.AvatarMaker.AWSpineColorsList em resources.assets).

Listas usadas: Skin (tom de pele: DisplayColor = cor-base, Colors = sombras), Eyes (Colors[0] = iris, Colors[1] = brilho),
GeneralWithoutGradient (roupas de cor unica). Saidas:
  client/.../Resources/AvatarSpine/palettes.json
  client/.../Scripts/Core/Avatar/AvatarPaletteData.cs  (contagens e indices padrao, para validar o save sem Resources)
uso: tools/venv/bin/python tools/avatar_palette_export.py
"""
import gzip
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UNITY = ROOT / 'client/AvatarWorldClient/Assets'
LISTS = {'skin': 'Skin', 'eyes': 'Eyes', 'general': 'GeneralWithoutGradient'}
# cores que o cliente usava fixas antes das paletas: o padrao e a entrada mais proxima delas
DEFAULT_SKIN = (1.0, 0.824, 0.675)
DEFAULT_EYES = (0.22, 0.44, 0.57)
DEFAULT_ITEM = (0.18, 0.11, 0.08)  # marrom escuro: cor inicial de sobrancelhas e outros itens _color


def rgb(c):
    return [round(c['r'], 4), round(c['g'], 4), round(c['b'], 4)]


def nearest(entries, target):
    return min(range(len(entries)), key=lambda i: sum((a - b) ** 2 for a, b in zip(entries[i]['display'], target)))


def main():
    found = {}
    for line in gzip.open(ROOT / 'out/mb/PWC.AvatarMaker.AWSpineColorsList.jsonl.gz', 'rt'):
        r = json.loads(line)
        if r['m_Name'] in LISTS.values():
            raw = r['AvatarMakerColors']
            found[r['m_Name']] = json.loads(raw) if isinstance(raw, str) else raw
    out = {}
    for key, name in LISTS.items():
        # JsonUtility nao le arrays de arrays: cada cor e um objeto {"c": [r,g,b]}
        out[key] = [{'display': rgb(e['DisplayColor']), 'colors': [{'c': rgb(c)} for c in e['Colors']]} for e in found[name]]
    out['defaultSkin'] = nearest(out['skin'], DEFAULT_SKIN)
    out['defaultEyes'] = nearest(out['eyes'], DEFAULT_EYES)
    out['defaultItem'] = nearest(out['general'], DEFAULT_ITEM)
    (UNITY / 'Resources/AvatarSpine/palettes.json').write_text(json.dumps(out, separators=(',', ':')), encoding='utf-8')
    (UNITY / 'Scripts/Core/Avatar/AvatarPaletteData.cs').write_text(
        '// <auto-generated> por tools/avatar_palette_export.py - nao editar a mao. </auto-generated>\n'
        'namespace AvatarWorld.Core.Avatar\n{\n'
        '    /// <summary>Tamanho e indices padrao das paletas do editor (Resources/AvatarSpine/palettes.json).</summary>\n'
        '    public static class AvatarPaletteData\n    {\n'
        f'        public const int SkinCount = {len(out["skin"])};\n'
        f'        public const int EyesCount = {len(out["eyes"])};\n'
        f'        public const int GeneralCount = {len(out["general"])};\n'
        f'        public const int DefaultSkin = {out["defaultSkin"]};\n'
        f'        public const int DefaultEyes = {out["defaultEyes"]};\n'
        f'        public const int DefaultItemColor = {out["defaultItem"]};\n'
        '    }\n}\n', encoding='utf-8')
    print({k: len(v) for k, v in out.items() if isinstance(v, list)}, 'defaultSkin', out['defaultSkin'], 'defaultEyes', out['defaultEyes'])


if __name__ == '__main__':
    main()
